import { mkdirSync, writeFileSync, chmodSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from '../server/config.mjs';
import { launcherEnvironment, shellQuote as quote } from './launcher-settings.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
if (process.platform !== 'darwin') throw new Error('This installer currently targets KiCad 10 on macOS.');
const destination = join(homedir(), 'Documents/KiCad/10.0/plugins/local_benchline_preview');
if (existsSync(destination)) throw new Error(`Already installed at ${destination}; refusing to overwrite.`);
mkdirSync(destination, { recursive:true });
writeFileSync(join(destination, 'plugin.json'), JSON.stringify({ identifier:'local.benchline.preview', name:'Benchline', description:'AI workspace with live board context and A2UI visuals.', runtime:{type:'exec'}, actions:[{identifier:'open-benchline',name:'Benchline',description:'Open Benchline',entrypoint:'launch', 'show-button':true,scopes:['pcb']}] },null,2)+'\n');
const exports=Object.entries(launcherEnvironment(config)).map(([key,value])=>`export ${key}=${quote(value)}`).join('\n');
writeFileSync(join(destination, 'launch'), '#!/bin/sh\nexport PATH='+quote(dirname(process.execPath))+':"$PATH"\n'+exports+'\nexec '+quote(process.execPath)+' '+quote(join(root,'scripts/launch.mjs'))+'\n');
chmodSync(join(destination, 'launch'), 0o755);
console.log(`Installed ${destination}\nRestart the KiCad PCB Editor to discover Benchline. Existing companion plugins were not changed.`);
