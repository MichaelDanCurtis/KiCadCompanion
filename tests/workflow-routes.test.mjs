import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {once} from 'node:events';
import {createProjectWorkflows,workflowRoutes} from '../server/workflow-projects.mjs';
import {WorkspaceViews,workspaceViewRoutes} from '../server/workspace-views.mjs';

test('workflow routes enforce controller ownership and release drains an admitted proposal before transfer',async t=>{
  const root=await mkdtemp(join(tmpdir(),'benchline-workflow-routes-'));
  const project={hash:'a'.repeat(64),manifest:{id:randomUUID(),name:'Route fixture',revision:1,requirements:[],artifacts:[]},local:{epoch:randomUUID(),observations:{}}};
  const projects={open:async()=>structuredClone(project)};
  const workflows=createProjectWorkflows({path:join(root,'workflow.sqlite'),projects});
  const views=new WorkspaceViews({projects,quiesce:async()=>{await Promise.allSettled([...workflows.pending]);}});
  const owner=await views.join({projectId:project.manifest.id,expectedManifestHash:project.hash,expectedEpoch:project.local.epoch});
  let entered,release;const started=new Promise(r=>entered=r),hold=new Promise(r=>release=r);
  const app=express();app.use(express.json());workspaceViewRoutes(app,views);
  workflowRoutes(app,{...workflows,views,propose:async(...args)=>{entered();await hold;return workflows.propose(...args);}});
  app.use((error,req,res,next)=>res.status(error.status||400).json({error:error.message}));
  const server=app.listen(0,'127.0.0.1');await once(server,'listening');
  t.after(async()=>{release();server.closeAllConnections();await new Promise(r=>server.close(r));await workflows.store.close();await rm(root,{recursive:true,force:true});});
  const origin=`http://127.0.0.1:${server.address().port}`;
  const post=(path,data,token)=>fetch(origin+path,{method:'POST',headers:{'Content-Type':'application/json',...(token?{'X-Benchline-Controller':token}:{})},body:JSON.stringify(data)});
  const path=`/api/workflows/projects/${project.manifest.id}/propose`,input={requestId:randomUUID(),expectedHash:project.hash};
  for(const url of [path,path.toUpperCase()+'/'])assert.equal((await post(url,input)).status,403);
  const proposal=post(path,input,owner.controllerToken);await started;assert.equal(workflows.pending.size,1);
  const releasing=views.release(owner.viewId,owner.controllerToken);
  assert.equal((await views.join({projectId:project.manifest.id,expectedManifestHash:project.hash,expectedEpoch:project.local.epoch})).role,'observer');
  assert.equal((await post(path,{...input,requestId:randomUUID()},owner.controllerToken)).status,403);
  release();assert.equal((await proposal).status,200);await releasing;assert.equal(workflows.pending.size,0);
  assert.equal(workflows.store.list(project.manifest.id).length,1);
  const next=await views.join({projectId:project.manifest.id,expectedManifestHash:project.hash,expectedEpoch:project.local.epoch});assert.equal(next.role,'controller');
  const plan=workflows.store.list(project.manifest.id)[0];
  assert.equal((await post(`/api/workflows/${plan.id}/activate`,{requestId:randomUUID()},owner.controllerToken)).status,403);
  assert.equal((await post(`/api/workflows/${plan.id}/activate`,{requestId:randomUUID()},next.controllerToken)).status,200);
});
